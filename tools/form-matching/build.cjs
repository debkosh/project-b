// Bundles core/forms/page/matching/entry.js with DuckDuckGo's matching at <their checkout>
// into core/forms/page/matching.gen.js (tools/form-matching.sh runs it).
// node tools/form-matching/build.cjs <their checkout> <their commit> <its date>
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '../..');
const [theirs, commit, date] = process.argv.slice(2);
const esbuild = require(path.join(root, 'shell/node_modules/esbuild'));
const out = path.join(root, 'core/forms/page/matching.gen.js');
esbuild
  .build({
    entryPoints: [path.join(root, 'core/forms/page/matching/entry.js')],
    bundle: true,
    format: 'iife',
    minify: true,
    legalComments: 'none',
    target: 'chrome120',
    write: false,
    logLevel: 'warning',
    alias: { ddg: theirs, '@duckduckgo/content-scope-scripts/injected/src/utils': path.join(root, 'core/forms/page/matching/stub.js') },
  })
  .then((r) => {
    const head = `// Generated by tools/form-matching.sh: do not edit. DuckDuckGo's field matching\n// (github.com/duckduckgo/duckduckgo-autofill at ${commit}, ${date}; Apache License 2.0,\n// core/forms/page/matching/LICENSE) with core/forms/page/matching/entry.js.\n`;
    fs.writeFileSync(out, head + r.outputFiles[0].text);
    console.log(fs.statSync(out).size);
  })
  .catch((e) => {
    console.error(String(e.message).split('\n').slice(0, 8).join('\n'));
    process.exit(1);
  });
